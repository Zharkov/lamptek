"""
Конфиг gunicorn для этого проекта.

preload_app=True — app.py импортируется один раз в мастер-процессе ДО форка
воркеров. Без этого при нескольких воркерах (-w 2+) каждый воркер независимо
импортирует app.py и пытается создать таблицы БД одновременно — гонка,
приводящая к "table ... already exists" при старте.

post_fork — после preload воркеры наследуют от мастера открытые соединения
SQLAlchemy/SQLite, которые нельзя расшаривать между процессами. Здесь мы
закрываем унаследованные соединения сразу после форка, чтобы каждый воркер
завёл свои собственные.
"""
bind = '127.0.0.1:28936'
workers = 2
preload_app = True


def post_fork(server, worker):
    from app import app, db
    with app.app_context():
        db.engine.dispose()
